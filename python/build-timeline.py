def isMissing(ep, key):
  if key == 'rss':
    return ep['rss_item'] == False
  return ep['missing'][key] == 'none'


def runsOf(episodes, key):
  # Consecutive episodes missing the same thing
  runs = []
  current = []
  for ep in episodes:
    if isMissing(ep, key):
      current.append(ep)
    elif len(current) > 0:
      runs.append(current)
      current = []
  if len(current) > 0:
    runs.append(current)
  return runs


def monthsBetween(a, b):
  months = []
  y, m = a.year, a.month
  while (y, m) <= (b.year, b.month):
    months.append((y, m))
    m += 1
    if m > 12:
      y, m = y + 1, 1
  return months


def waybackLinks(a, b):
  links = []
  for y, m in monthsBetween(a, b):
    if y in PERMALINK_YEARS:
      links.append(f"[{y}-{m:02}](https://web.archive.org/web/*/{PERMALINK_PREFIX}/{y}/{m:02}/*)")
  return " ".join(links)


