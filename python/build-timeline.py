def writeText(filepath, lines):
  with open(filepath, "w") as f:
    f.write("\n".join(lines))


def isSet(value):
  if value == None:
    return False
  if str(value).strip() == '':
    return False
  if str(value).startswith(PLACEHOLDER):
    return False
  return True


def parseDateTime(value):
  # Returns (datetime or None, date or None)
  if value == None:
    return None, None

  if isinstance(value, datetime):
    return value, value.date()

  if isinstance(value, date):
    return None, value

  value = re.sub(r"\s+", " ", str(value).strip())

  formats = [
    "%a %b %d %H:%M:%S %Y %z",
    "%a, %d %b %Y %H:%M:%S %z",
    "%a, %d %b %Y %H:%M:%S %Z",
    "%Y-%m-%dT%H:%M:%S%z",
  ]
  for fmt in formats:
    try:
      dt = datetime.strptime(value, fmt)
      return dt, dt.date()
    except ValueError:
      pass

  m = re.match(r"^(\d{4})-(\d{2})-(\d{2})$", value)
  if m:
    try:
      return None, date(int(m.group(1)), int(m.group(2)), int(m.group(3)))
    except ValueError:
      pass

  return None, None


def dateFromFilename(filename):
  if filename == None:
    return None
  m = re.search(r"(\d{4})-(\d{2})-(\d{2})", str(filename))
  if m:
    try:
      return date(int(m.group(1)), int(m.group(2)), int(m.group(3)))
    except ValueError:
      pass
  return None


def episodeKey(value):
  value = str(value).strip()
  if value.isdigit():
    return f"{int(value):03}"
  return value


def splitRow(line):
  cells = line.strip().strip('|').split('|')
  return [c.strip() for c in cells]


def findSection(lines):
  # Returns (start, end) line indexes of the episode table, or of the
  # generated block when it exists
  heading = None
  for i, line in enumerate(lines):
    if line.strip() == SECTION_HEADING:
      heading = i
      break
  if heading == None:
    return None, None

  section_end = len(lines)
  for i in range(heading + 1, len(lines)):
    if lines[i].startswith('## '):
      section_end = i
      break

  for i in range(heading + 1, section_end):
    if lines[i].strip() == MARKER_BEGIN:
      for j in range(i + 1, section_end):
        if lines[j].strip() == MARKER_END:
          return i, j + 1

  start = None
  end = None
  for i in range(heading + 1, section_end):
    if lines[i].startswith('|'):
      if start == None:
        start = i
      end = i + 1
    elif start != None:
      break
  return start, end


def readCurated(lines, start, end):
  # First table in the section whose header starts with Episode / No
  result = {}
  duplicates = []
  in_table = False
  for line in lines[start:end]:
    if not line.startswith('|'):
      in_table = False
      continue
    cells = splitRow(line)
    if cells[0] in ['Episode', 'No']:
      in_table = len(cells) >= 3 and cells[1] == 'Date'
      continue
    if not in_table or not re.match(r"^\d{1,3}$", cells[0]):
      continue
    episode = episodeKey(cells[0])
    _, d = parseDateTime(cells[1])
    title = cells[2].replace('\\|', '|') if cells[2] != '' else None
    if episode in result:
      duplicates.append((episode, cells[1], cells[2]))
      continue
    result[episode] = {'date': d, 'title': title}
  return result, duplicates


def numbersInText(*texts):
  # Explicit episode numbers like '#500' or 'DSC-749-2008-04-18'
  numbers = set()
  for text in texts:
    if text == None:
      continue
    for m in re.finditer(r"(?:#|DSC-)(\d{3})\b", str(text)):
      numbers.add(m.group(1))
  return numbers


def daysApart(a, b):
  if a == None or b == None:
    return None
  return abs((a - b).days)


def localFiles(d):
  if d == None:
    return {'srt': False, 'vtt': False, 'img': 0, 'shownotes': False}
  iso = d.isoformat()
  year = iso[:4]
  return {
    'srt': os.path.isfile(f"{SRT_DIR}{year}/DSC-{iso}.srt"),
    'vtt': os.path.isfile(f"{VTT_DIR}{year}/DSC-{iso}.vtt"),
    'img': len(glob.glob(f"{IMG_DIR}{year}/DSC-{iso}-*")),
    'shownotes': len(glob.glob(f"{SHOWNOTES_DIR}{year}/DSC-{iso}*")) > 0,
  }


MONTHS = ['january', 'february', 'march', 'april', 'may', 'june', 'july',
  'august', 'september', 'october', 'november', 'december']


def validDate(y, m, d):
  try:
    result = date(int(y), int(m), int(d))
  except ValueError:
    return None
  if 2004 <= result.year <= 2013:
    return result
  return None


def episodeDateFromURL(url):
  # The date a show was recorded, as named in its enclosure filename
  name = os.path.basename(str(url or ''))
  patterns = [
    (r"(20\d\d)-(\d\d)-(\d\d)", 'ymd'),       # DSC-2005-05-18.mp3
    (r"(\d\d)-(\d\d)-(20\d\d)", 'mdy'),       # dailysourcecode-37957-11-20-2006.mp3
    (r"(?<!\d)(20\d\d)(\d\d)(\d\d)(?!\d)", 'ymd'),  # dailySourceCode-20040813-.., DSC20041230
    (r"(?<!\d)(\d\d)(\d\d)(200\d)(?!\d)", 'mdy'),   # dailySourceCode09032004.mp3
  ]
  for pattern, order in patterns:
    m = re.search(pattern, name)
    if m == None:
      continue
    a, b, c = m.groups()
    if order == 'ymd':
      found = validDate(a, b, c)
    else:
      # MMDDYYYY, or DDMMYYYY when the month is impossible (DSC-14092004)
      found = validDate(c, a, b) or validDate(c, b, a)
    if found != None:
      return found
  return None


def episodeDateFromTitle(title):
  # "Daily Source Code for Friday May 18th 2005"
  m = re.search(r"(?i)\b(" + "|".join(MONTHS) + r")\s+(\d{1,2})(?:st|nd|rd|th)?,?\s+(20\d\d)\b", str(title or ''))
  if m == None:
    return None
  return validDate(m.group(3), MONTHS.index(m.group(1).lower()) + 1, m.group(2))


WEEKDAYS = ['monday', 'tuesday', 'wednesday', 'thursday', 'friday', 'saturday', 'sunday']

ORDINALS = {
  'first': 1, 'second': 2, 'third': 3, 'fourth': 4, 'fifth': 5, 'sixth': 6,
  'seventh': 7, 'eighth': 8, 'ninth': 9, 'tenth': 10, 'eleventh': 11,
  'twelfth': 12, 'thirteenth': 13, 'fourteenth': 14, 'fifteenth': 15,
  'sixteenth': 16, 'seventeenth': 17, 'eighteenth': 18, 'nineteenth': 19,
  'twentieth': 20, 'thirtieth': 30,
}
for _n, _word in enumerate(['first', 'second', 'third', 'fourth', 'fifth', 'sixth', 'seventh', 'eighth', 'ninth'], 1):
  ORDINALS[f"twenty-{_word}"] = 20 + _n
  ORDINALS[f"twenty {_word}"] = 20 + _n
ORDINALS['thirty-first'] = 31
ORDINALS['thirty first'] = 31

DAY_PATTERN = r"\d{1,2}(?:st|nd|rd|th)?|" + "|".join(sorted(map(re.escape, ORDINALS), key=len, reverse=True))

# "Friday June 17th 2005", "for July 6, 2005", "June the 17th"
SPOKEN_DATE = re.compile(
  r"(?i)(?:\b(" + "|".join(WEEKDAYS) + r")\b[\s,]+(?:the\s+)?)?\b(" + "|".join(MONTHS) + r")\s+(?:the\s+)?("
  + DAY_PATTERN + r")\b(?:[\s,]+(20\d\d))?"
)
# "Friday the 17th"
SPOKEN_WEEKDAY_DAY = re.compile(r"(?i)\b(" + "|".join(WEEKDAYS) + r")\b[\s,]+the\s+(" + DAY_PATTERN + r")\b")
# "it's Friday"
SPOKEN_WEEKDAY = re.compile(
  r"(?i)\b(?:it'?s|it is|happy|this is|on this|good|beautiful|lovely)\s+(?:a\s+)?(?:\w+\s+)?(" + "|".join(WEEKDAYS) + r")\b"
)
SPOKEN_CUE = re.compile(r"(?i)(today|it'?s|this is|source code|for|happy)\W*(\w+\W+){0,3}$")

# Lines of transcript text read, about the first 8 minutes
TRANSCRIPT_INTRO_LINES = 200


def spokenDay(value):
  return int(re.match(r"\d+", value).group()) if value[0].isdigit() else ORDINALS.get(value.lower())


def readTranscriptIntro(d):
  # Transcripts are named after the date of the local mp3
  if d == None:
    return None
  iso = d.isoformat()
  for path in [f"{SRT_DIR}{iso[:4]}/DSC-{iso}.srt", f"{VTT_DIR}{iso[:4]}/DSC-{iso}.vtt"]:
    if os.path.isfile(path):
      with open(path, errors='replace') as fp:
        lines = [l.strip() for l in fp if l.strip() and '-->' not in l and not l.strip().isdigit() and l.strip() != 'WEBVTT']
      return " ".join(lines[:TRANSCRIPT_INTRO_LINES])
  return None


def spokenDate(text, reference):
  # What Adam says the date is, near the date of the file. Returns
  # ('date', date, phrase), ('weekday', name, phrase) or None. A named
  # weekday must agree with the date, a date without one needs a cue such as
  # "it's" or "source code for" just before it.
  if text == None or reference == None:
    return None

  for m in SPOKEN_DATE.finditer(text):
    weekday, month, day, year = m.group(1), m.group(2), m.group(3), m.group(4)
    day = spokenDay(day)
    if not day:
      continue
    month = MONTHS.index(month.lower()) + 1
    best = None
    for y in ([int(year)] if year else [reference.year - 1, reference.year, reference.year + 1]):
      candidate = validDate(y, month, day)
      if candidate != None and (best == None or daysApart(candidate, reference) < daysApart(best, reference)):
        best = candidate
    if best == None or daysApart(best, reference) > 45:
      continue
    if weekday != None:
      if WEEKDAYS[best.weekday()] != weekday.lower():
        continue
    elif not SPOKEN_CUE.search(text[max(0, m.start() - 40):m.start()]):
      continue
    return ('date', best, m.group(0))

  for m in SPOKEN_WEEKDAY_DAY.finditer(text):
    weekday, day = m.group(1).lower(), spokenDay(m.group(2))
    if not day:
      continue
    for offset in (0, -1, 1):
      y, month = reference.year, reference.month + offset
      if month == 0:
        y, month = y - 1, 12
      if month == 13:
        y, month = y + 1, 1
      candidate = validDate(y, month, day)
      if candidate != None and WEEKDAYS[candidate.weekday()] == weekday and daysApart(candidate, reference) <= 20:
        return ('date', candidate, m.group(0))

  m = SPOKEN_WEEKDAY.search(text)
  if m != None:
    return ('weekday', m.group(1).lower(), m.group(0))
  return None


def readSnapshots(rss_dir):
  # Every saved feed snapshot: which episode dates its DSC items cover.
  # The episode (recording) date comes from the enclosure name or title, the
  # pubDate is only used when neither has one, it can be days later.
  snapshots = []
  seen = set()
  for path in sorted(glob.glob(os.path.join(rss_dir, '**', '*'), recursive=True)):
    if not os.path.isfile(path) or '/episodes/' in path:
      continue
    name = os.path.basename(path)
    if name in seen:
      continue
    seen.add(name)
    try:
      with open(path, errors='replace') as fp:
        content = fp.read()
    except OSError:
      continue

    episode_dates = set()
    pub_dates = set()
    items = 0
    for item in re.findall(r"<item[ >].*?</item>", content, flags=re.S):
      enclosure = re.search(r"<enclosure[^>]*url=\"([^\"]+)\"", item)
      if enclosure == None or not re.search(r"(?i)dailysourcecode|/DSC|source.?code", enclosure.group(1) + item[:500]):
        continue
      items += 1
      title = re.search(r"<title>\s*(.*?)\s*</title>", item, flags=re.S)
      recorded = episodeDateFromURL(enclosure.group(1)) or episodeDateFromTitle(title.group(1) if title else None)
      pub = re.search(r"<pubDate>\s*(.*?)\s*</pubDate>", item, flags=re.S)
      published = parseDateTime(pub.group(1))[1] if pub != None else None
      if recorded != None:
        episode_dates.add(recorded)
      elif published != None:
        pub_dates.add(published)

    dates = episode_dates | pub_dates
    if len(dates) == 0:
      continue
    snapshots.append({
      'name': os.path.relpath(path, rss_dir),
      'taken': dateFromFilename(name) or max(dates),
      'first': min(dates),
      'last': max(dates),
      'episode_dates': episode_dates,
      'pub_dates': pub_dates,
      'items': items,
    })
  return snapshots


def readPostDates(pattern):
  # Episode dates of the posts in json/dsc-posts-*.json (python/update-episodes-from-posts.py)
  dates = set()
  for path in sorted(glob.glob(pattern)):
    with open(path) as fp:
      posts = json.load(fp)
    for post in posts:
      enclosure = post.get('enclosure') or {}
      recorded = episodeDateFromURL(enclosure.get('url')) if enclosure.get('url') else None
      recorded = recorded or episodeDateFromTitle(post.get('title'))
      if recorded != None:
        dates.add(recorded)
  return dates


def snapshotDepth(snapshots, d):
  # Median number of DSC items a snapshot holds, near date d
  near = [s for s in snapshots if daysApart(s['taken'], d) <= 365]
  if len(near) == 0:
    near = snapshots
  counts = sorted(s['items'] for s in near)
  return counts[len(counts) // 2] if counts else 0


def get(data, *keys):
  for key in keys:
    if not isinstance(data, dict):
      return None
    data = data.get(key)
  return data


def collectEpisode(episode, lookup, curated):
  stub, stub_error = readYAML(f"{EPISODE_DIR}{episode}.yaml")
  frag, frag_error = readYAML(f"{EPISODE_EXTRACT_DIR}{episode}.yaml")

  info = {
    'episode': episode,
    'stub': stub,
    'frag': frag,
    'errors': [],
    'curated': curated.get(episode) or {'date': None, 'title': None},
  }
  if stub_error:
    info['errors'].append(f"yaml/episodes/{episode}.yaml: {stub_error}")
  if frag_error:
    info['errors'].append(f"rss/episodes/{episode}.yaml: {frag_error}")

  # Episode (recording) date and publish date are different things: a show
  # recorded one day can be published days later. A date only pubDate in the
  # episode yaml is a placeholder for the episode date.
  filename = get(stub, 'fileinfo', 'filename')
  stub_dt, stub_pub = parseDateTime(get(stub, 'pubDate'))
  frag_dt, frag_pub = parseDateTime(get(frag, 'pubDate'))
  frag_recorded = episodeDateFromURL(get(frag, 'enclosure', 'url')) or episodeDateFromTitle(get(frag, 'title'))

  dates = {
    'file': dateFromFilename(filename),
    'stub': stub_pub if stub_dt == None else None,
    'lookup': parseDateTime(lookup.get(episode))[1],
    'rss': frag_recorded,
    'timeline': info['curated']['date'],
  }
  info['dates'] = dates
  info['frag_pub'] = frag_pub
  info['filename'] = filename

  # Local material is keyed on the date of the local mp3
  local_date = dates['file'] or dates['stub']
  info['local'] = localFiles(local_date)

  # The date Adam says in the show
  info['said'] = spokenDate(readTranscriptIntro(dates['file']), dates['file'])
  if info['said'] != None and info['said'][0] == 'date':
    dates['said'] = info['said'][1]
  else:
    dates['said'] = None

  # Does the extracted fragment describe the same show as the local mp3?
  # Compared on the fragment's own episode date, its pubDate as a fallback
  # (published up to a week later).
  reference = local_date or dates['timeline']
  info['frag_matches'] = None
  if frag != None and reference != None:
    if frag_recorded != None:
      info['frag_matches'] = daysApart(reference, frag_recorded) <= DATE_TOLERANCE
    elif frag_pub != None:
      info['frag_matches'] = -DATE_TOLERANCE <= (frag_pub - reference).days <= PUBLISH_LAG

  info['date'] = local_date or dates['timeline'] or dates['rss'] or dates['lookup']

  # Publish timestamp only when it is a real one
  published = None
  if stub_dt != None:
    published = stub_dt
  elif frag_dt != None and info['frag_matches'] != False:
    published = frag_dt
  info['published'] = published.isoformat() if published != None else None
  info['lag'] = None
  if published != None and info['date'] != None:
    info['lag'] = (published.date() - info['date']).days

  # Conflicting episode dates between sources
  values = [v for v in dates.values() if v != None]
  info['conflict'] = any(daysApart(a, b) > DATE_TOLERANCE for a in values for b in values)

  info['numbers'] = numbersInText(
    get(frag, 'title'),
    get(frag, 'description'),
    get(frag, 'itunes', 'summary'),
  )

  info['missing'] = missingFields(stub, frag, info)

  return info


def missingFields(stub, frag, info):
  # Each field: 'ok' (in episode yaml), 'frag' (only in a matching extracted fragment), 'none'
  usable_frag = frag if info['frag_matches'] != False else None

  def state(stub_value, frag_value=None):
    if isSet(stub_value):
      return 'ok'
    if usable_frag != None and isSet(frag_value):
      return 'frag'
    return 'none'

  description = get(stub, 'description')
  if description != None and re.sub(r"(\\n)?Duration: [0-9:]+", "", str(description)).strip() == '':
    description = None

  stub_url = get(stub, 'enclosure', 'url')
  if stub_url != None and not re.match(r"^https?://", str(stub_url)):
    stub_url = None

  stub_pub = get(stub, 'pubDate')
  if parseDateTime(stub_pub)[0] == None:
    stub_pub = None

  title = info['curated']['title']
  if title == 'Daily Source Code':
    title = None

  local = info['local']

  fields = {
    'pubDate': state(stub_pub, get(usable_frag, 'pubDate')),
    'title': 'ok' if title != None else 'none',
    'link': state(get(stub, 'link'), get(usable_frag, 'link')),
    'description': state(description, get(usable_frag, 'description')),
    'enclosure': state(stub_url, get(usable_frag, 'enclosure', 'url')),
    'image': state(get(stub, 'itunes', 'image', 'href'), get(usable_frag, 'itunes', 'image', 'href')),
    'duration': state(get(stub, 'itunes', 'duration')),
    'location': state(get(stub, 'podcast', 'location', 'geo')),
    'mp3': state(info['filename']),
    'transcript': 'ok' if local['srt'] or local['vtt'] else 'none',
    'episode_image': 'ok' if local['img'] > 0 else 'none',
    'shownotes': 'ok' if local['shownotes'] else 'none',
  }
  return fields


